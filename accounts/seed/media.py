def photo(pid, w, h, faces=False):
    # auto=format serves WebP/AVIF to browsers that take them, JPEG otherwise.
    crop = "faces,center" if faces else "entropy"
    return f"https://images.unsplash.com/photo-{pid}?auto=format&fit=crop&crop={crop}&w={w}&h={h}&q=70"


def avatar(pid):
    return photo(pid, 320, 320, faces=True)


def post_image(pid):
    # Sharp on a phone screen, light enough for mobile data.
    return photo(pid, 800, 800)


def story_image(pid):
    return photo(pid, 720, 1280)
